/**
 * ITA III is a proposal, not an agreement, and it reaches back into the materials the guide leaves
 * out: "Raw materials ... used in the production of the ICT products, are not covered in the current
 * RDTII framework." Its chemicals, plastics and rubber (HS chapters 25 to 40) are those materials --
 * epoxy resins, rubber accelerators, silicones -- so they are dropped from it. ITA I and II are kept
 * whole, because what an agreement covers is not ours to narrow, and the manufactured metal and
 * glass goods ITA III adds are the "ICT-related goods" the guide names by example.
 */
const MATERIALS = (code: string): boolean => Number(code.slice(0, 2)) <= 40;

const CODES = new Set<string>([...ITA_I, ...ITA_II, ...ITA_III.filter((c) => !MATERIALS(c))]);

/**
 * A tariff code as a customs instrument writes one: a four-digit heading followed by at least one
 * more pair of digits, run together or spaced or dotted -- "85340000", "8534 0000", "9001 10 00",
 * "8504.22". A bare four-digit number is a year or a section as often as a heading, so it is never
 * read as one.
 */
const TARIFF_CODE = /(?<![\d.])(\d{4})[ .]?(\d{2})(?:[ .]?(\d{2}))?(?:[ .]?\d{2})?(?![\d])/g;

/** The ICT tariff codes this text states, as the six digits (or the heading) that matched. */
export function ictTariffCodes(text: string | null | undefined): string[] {
  if (!text) return [];
  const found = new Set<string>();
  for (const m of text.matchAll(TARIFF_CODE)) {
    const heading = m[1]!;
    const chapter = Number(heading.slice(0, 2));
    // Goods are chapters 1 to 97; the lists start at 28. A year such as 2024 10 is chapter 20.
    if (chapter < 25 || chapter > 97) continue;
    const six = heading + m[2]!;
    if (CODES.has(six)) found.add(six);
    else if (CODES.has(heading)) found.add(heading);
  }
  return [...found].sort();
}

/** The field evidence carries, present only where the provision states an ICT tariff code. */
export function tariffCodesOf(text: string | null | undefined): { ictTariffCodes?: string[] } {
  const codes = ictTariffCodes(text);
  return codes.length ? { ictTariffCodes: codes } : {};
}
